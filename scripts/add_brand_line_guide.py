TH = 'class="text-left font-medium text-ink border-b border-line py-2 pr-3"'
TD = 'class="border-b border-line/60 py-2 pr-3 align-top"'


def block(ja, rows):
    price = any(c for _, _, c in rows)  # 価格がマスタに無いブランドは列ごと出さない（推測で埋めない）
    cell = lambda c: f'<td {TD} style="white-space:nowrap">{c or "店頭でご案内"}</td>' if price else ''
    tr = ''.join(f'<tr><td {TD}>{a}</td><td {TD} style="white-space:nowrap">{b}</td>{cell(c)}</tr>' for a, b, c in rows)
    th3 = f'<th {TH}>定価（税込）</th>' if price else ''
    note = '定価は1本の価格です 在庫は店舗で異なるので 取り置きは各店舗へご相談ください' if price else '価格と在庫は店舗でご案内します 取り置きは各店舗へご相談ください'
    return f'''{MARK_S}
    <h2 id="line-guide" class="mt-10 font-serif text-[19px] sm:text-[22px] text-ink">悩みから選ぶ {ja}のライン早見表</h2>
    <p class="mt-4 text-[13.5px] sm:text-[14px] text-charcoal/80">{ja}はラインごとに向く髪が決まっています いちばん気になることから選ぶと迷いません</p>
    <div class="mt-4 overflow-x-auto" data-track-view="line_guide"><table class="w-full text-[13.5px] text-charcoal/80 border-collapse"><thead><tr><th {TH}>気になること</th><th {TH}>ライン</th>{th3}</tr></thead><tbody>{tr}</tbody></table></div>
    <p class="mt-3 text-[12.5px] text-charcoal/65">{note}　<a href="finder.html" class="text-gold hover:underline underline-offset-4" data-track-click="line_guide_finder">髪のタイプから選ぶなら 髪格診断（3分・無料）→</a></p>
    {MARK_E}
    '''

for slug, (ja, rows) in G.items():
    p = f'{slug}.html'
    t = open(p, encoding='utf-8').read()
    t = re.sub(re.escape(MARK_S) + r'.*?' + re.escape(MARK_E) + r'\s*', '', t, flags=re.S)
    i = t.index('<h2 id="where-to-buy"')
    t = t[:i] + block(ja, rows) + t[i:]
    open(p, 'w', encoding='utf-8').write(t)
    print(p, len(rows))
