def rep_title(s, new):
    return re.sub(r'<title>[^<]*</title>', '<title>' + new + '</title>', s, count=1)

def rep_desc(s, new):
    return re.sub(r'(<meta\s+name="description"\s+content=")[^"]*(")', lambda m: m.group(1) + new + m.group(2), s, count=1)

def rep_h1(s, old, new, tr=None):
    """H1 の中身（innerHTML）を差し替える。<br> はそのまま。
    H1 に data-i18n の鍵が付いていれば 辞書の ja と4言語も同じ意味にそろえる
    （鍵は中身の hash なので 変えると台帳とはずれるが 辞書に値があれば build は当てる）"""
    m = re.search(r'<h1\b([^>]*)>\s*' + re.escape(old) + r'\s*</h1>', s)
    if not m: return s
    s = s[:m.start()] + '<h1' + m.group(1) + '>' + new + '</h1>' + s[m.end():]
    km = re.search(r'data-i18n="([^"]+)"', m.group(1))
    if km:
        key = km.group(1)
        vals = {'ja': new}; vals.update(tr or {})
        for lang, v in vals.items():
            s = re.sub(r'("' + lang + r'"\s*:\s*\{[^{}]*?"' + re.escape(key) + r'"\s*:\s*)"(?:[^"\\]|\\.)*"',
                       lambda mm: mm.group(1) + json.dumps(v, ensure_ascii=False), s, count=1, flags=re.S)
    return s

def sync_dict(s, title, desc):
    # 辞書の ja.meta.title / ja.meta.description を同じ値にする（言語版の生成元にはならないが 整合のため）
    def q(v): return json.dumps(v, ensure_ascii=False)
    s2 = re.sub(r'("ja"\s*:\s*\{[^{}]*?"meta\.title"\s*:\s*)"(?:[^"\\]|\\.)*"', lambda m: m.group(1) + q(title), s, count=1, flags=re.S)
    s2 = re.sub(r'("ja"\s*:\s*\{[^{}]*?"meta\.description"\s*:\s*)"(?:[^"\\]|\\.)*"', lambda m: m.group(1) + q(desc), s2, count=1, flags=re.S)
    return s2

n = 0; skipped = []
for f, (title, desc, h1, lede) in PLAN.items():
    if not os.path.exists(f): skipped.append(f); continue
    s = open(f, encoding='utf-8').read(); before = s
    # 商品名「つるりんちょ。」の句点だけは許す（文体ルールの例外）
    chk = lambda v: v.replace('つるりんちょ。', '')
    assert '。' not in chk(title) and '、' not in title, f + ' の title に句読点'
    assert '。' not in chk(desc) and '、' not in desc, f + ' の description に句読点'
    s = rep_title(s, title)
    s = rep_desc(s, desc)
    if h1 and ('>' + h1[1] + '</h1>') not in s:      # 既に新しい H1 なら何もしない（2回目の実行）
        s2 = rep_h1(s, h1[0], h1[1], h1[2] if len(h1) > 2 else None)
        if s2 == s: print(f'  ✘ {f}: H1「{h1[0]}」が見つからない');
        s = s2
    s = sync_dict(s, title, desc)
    if s != before:
        assert '</body>' in s, f + ' が壊れた'
        open(f, 'w', encoding='utf-8').write(s); n += 1
